#!/usr/bin/env python3
"""Render Stage 2 evidence report from the derived verification JSON."""
from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = Path(os.environ.get("THESIS_WORKSPACE_ROOT", Path(__file__).resolve().parents[3])).resolve()
DATA = ROOT / "article" / "data" / "json" / "final-audit-evidence.json"
OUT = ROOT / "article" / "drafts" / "final-audit" / "experimental-evidence-audit.md"


def main() -> None:
    d = json.loads(DATA.read_text(encoding="utf-8"))
    lines = [
        "# Stage 2 — Experimental Evidence Audit",
        "",
        "> Verified 2026-11-19 from raw exhibits and measurement records. "
        "Generated by `article/scripts/FinalAudit/verify_evidence.py`; "
        "derived JSON: `article/data/json/final-audit-evidence.json`. "
        "Raw evidence was read only.",
        "",
        "## 1. Scope and exclusions",
        "",
        "Only the designated **primary Node.js 26** runs are included: A–D at "
        "root commits `6d87bf3` (dev) and `8a1324b` (server), E at `8556513`, "
        "`6979e3f`, `530f751`. The old Node 24 run `0dcb418` and supporting "
        "core-0.3.1 run `3376d07` are excluded from primary results (they "
        "appear only as labeled corroboration in the manuscript).",
        "",
        "## 2. Verified run metadata (11 primary runs)",
        "",
        "| Phase | Run ID | Site | Runtime | Core / JS / ABI | WASM SHA-256 (first 16) | Rounds | Warmup | Config iterations |",
        "|---|---|---|---|---|---|---:|---:|---:|",
    ]
    for m in d["metadata"]:
        lines.append(
            f"| {m['phase']} | `{m['run_id']}` | {m['site']} | "
            f"{m['runtime']} | {m['core_version']} / {m['js_version']} / "
            f"{m['abi_version']} | `{str(m['artifact_sha256'])[:16]}` | "
            f"{m['rounds']} | {m['warmup']} | {m['config_iterations']} |")
    lines += [
        "",
        "All 11 records report `core_version = 0.3.2`, `js_version = 0.3.0`, "
        "`abi_version = 2026000302`, Node 26.13.1 / V8 14.6.202.34-node.40, "
        "and the same WASM artifact SHA-256 (`9795f2e8…`). Phase E `iterations = 20` "
        "is the **total requests per round for both engines** (10 + 10), "
        "not repetitions of one engine.",
        "",
        "## 3. Recomputed point estimates (43 primary cells)",
        "",
        "Method: `S = median(T_V8,1..15) / median(T_ZE,1..15)`, with A–D round "
        "values = harness `rounds_ms` (mean of reps) and E = median of 10 "
        "requests per engine per round. Recomputed values are compared to the "
        "canonical ledger at four decimals.",
        "",
        "| Phase | Site | Cell | Run ID | Recomputed S | Ledger S | Status |",
        "|---|---|---|---|---:|---:|---|",
    ]
    for c in d["checks"]:
        cell = c["key"].split("-", 3)[-1]
        lines.append(
            f"| {c['key'][0]} | {c['key'].split('-')[2]} | {cell} | "
            f"`{c['run_id']}` | {c['recomputed']:.4f} | {c['ledger']:.4f} | "
            f"{c['status']} |")
    echecks = [c for c in d["checks"] if c["key"].startswith("E")]
    lines += [
        "",
        f"**Result: {sum(1 for c in d['checks'] if c['status'] == 'MATCH')}/"
        f"{len(d['checks'])} cells MATCH.**",
        "",
        "## 4. Phase E request structure",
        "",
        "| Run | 15 rounds × 10 V8 + 10 ZE | Requests V8 / ZE | Unique body SHA-256 | Recomputed S |",
        "|---|---|---:|---:|---:|",
    ]
    for c in echecks:
        lines.append(
            f"| `{c['run_id']}` | {'PASS' if c['structure_15x20_10_10'] else 'FAIL'} | "
            f"{c['n_v8']} / {c['n_ze']} | {c['unique_body_hashes']} | "
            f"{c['recomputed']:.4f} |")
    lines += [
        "",
        "Each E run therefore contains exactly 15 paired rounds, 20 HTTP "
        "requests **in total** per round, 150 requests per engine, and 300 "
        "requests per run. One unique response hash per run confirms the "
        "byte-parity gate. The measured boundary is `GET /rekap` only "
        "(`saq-report/routes/rekapRoutes.js` L25–47; four repository "
        "reads/counts followed by `res.render('rekap-pilihan', …)`); no other "
        "route or request-body parsing is measured.",
        "",
        "## 5. Corpus provenance",
        "",
        "| Run / source | Store label in record | All six per-file SHA-256 equal `MANIFEST.json` |",
        "|---|---|---|",
    ]
    for c in d["corpus"]:
        lines.append(
            f"| `{c['run_id']}` | {c['store_label']} | "
            f"{'PASS' if c['all_six_match_manifest'] else 'FAIL'} |")
    lines += [
        "",
        "The six `store_sha256` values recorded in **all three Phase E runs** "
        "match `corpus/benchmarks/saq_payload_v1/MANIFEST.json` exactly, and "
        "the on-disk corpus files also match the manifest. Although the "
        "records label the server store as `LIVE store`, the recorded "
        "per-file hashes are identical to the generated anonymized corpus; "
        "there is **no evidence of live operational data**, and that phrase "
        "must not be used. Cross-site comparison remains a contextual "
        "narrative, not a pooled inference, per the run metadata note.",
        "",
        "## 6. Boundary classification",
        "",
        "| Phase | Measured boundary | Not measured |",
        "|---|---|---|",
        "| A | in-process full parse + materialization (`v8-parse` / `ze-parse`) | storage, HTTP |",
        "| B | in-process projection (`v8-selective` / `ze-project-selective`) | storage, HTTP |",
        "| C | in-process selective traversal (`v8-selective` / `ze-l1-traversal`) | storage, HTTP |",
        "| D | repository layer: warmed canonical Mongo bytes vs file bytes, one store at a time | parser-only isolation, cold-cache construction |",
        "| E | `GET /rekap` end-to-end on two byte-identical app instances | other routes, `express.json()` body parsing, parser-only latency |",
        "",
        "## 7. Stage 2 verdict",
        "",
        "**PASS** — all 43 primary point estimates reproduce from raw exhibits; "
        "E request structure and parity gate are verified; corpus hashes are "
        "identical across all runs and the manifest. Stage 3 (statistical "
        "audit) is authorized.",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
